#!/bin/sh
# Generates the files that depend on this machine and never live in git: the key
# that encrypts the Inspector's secret store, nginx's Basic Auth file, and the
# compose overlay mapping the MCP servers' hosts. Sourced by start.sh and
# restart.sh after compose.sh, from inside scripts/; extends their $COMPOSE.

# Once only: a new key would make the secrets already stored in ../data unreadable.
if [ ! -s .secret-key ]; then
    (umask 077 && openssl rand -hex 32 > .secret-key)
    echo "Generated scripts/.secret-key"
fi

# Every run, so a password changed in .env takes effect on the next start/restart.
UI_USERNAME=$(sed -n 's/^MCP_INSPECTOR_UI_USERNAME=//p' .env | tr -d '\r' | tr -d '"')
UI_PASSWORD=$(sed -n 's/^MCP_INSPECTOR_UI_PASSWORD=//p' .env | tr -d '\r' | tr -d '"')

if [ -z "$UI_USERNAME" ] || [ -z "$UI_PASSWORD" ]; then
    echo
    echo "===== ERROR: MCP_INSPECTOR_UI_USERNAME / MCP_INSPECTOR_UI_PASSWORD are empty ====="
    echo
    exit 1
fi

# Password through stdin, so it never shows up in the process list.
HASH=$(printf '%s' "$UI_PASSWORD" | openssl passwd -apr1 -stdin) || exit 1
# Truncate in place rather than replace: nginx's bind mount follows the inode.
printf '%s:%s\n' "$UI_USERNAME" "$HASH" > nginx/.htpasswd

# Compose cannot expand one variable into several list entries, so the hosts are
# written out as an overlay. Regenerated every run; only `start.sh` applies a
# change, because extra_hosts are set when the container is created.
SERVER_HOSTS=$(sed -n 's/^MCP_SERVER_HOSTS=//p' .env | tr -d '\r' | tr -d '"' | tr ',' ' ')

{
    echo "# Generated by prepare.sh from MCP_SERVER_HOSTS in .env — do not edit."
    echo "services:"
    echo "    mcp-inspector-app:"
    echo "        extra_hosts:"
    for HOST in $SERVER_HOSTS; do
        # Hostname characters only: the value is written into YAML unquoted.
        if ! printf '%s' "$HOST" | grep -Eq '^[A-Za-z0-9.-]+$'; then
            echo "===== ERROR: invalid host '$HOST' in MCP_SERVER_HOSTS =====" >&2
            exit 1
        fi
        echo "            - \"$HOST:host-gateway\""
    done
} > docker-compose.hosts.yml || exit 1

# With no hosts the list above is empty, which Compose rejects — drop the key.
if [ -z "$SERVER_HOSTS" ]; then
    printf '# Generated by prepare.sh — MCP_SERVER_HOSTS is empty.\nservices: {}\n' > docker-compose.hosts.yml
fi

COMPOSE="$COMPOSE -f docker-compose.hosts.yml"
